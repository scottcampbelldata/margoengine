const radians = Math.PI / 180;

function disc(u, v, radius, samples = 42) {
  return Array.from({ length: samples }, (_, index) => {
    const angle = 2 * Math.PI * index / samples;
    return [u + radius * Math.cos(angle), v + radius * Math.sin(angle)];
  });
}

function crescent(u, v, radius) {
  const half = 24;
  const curve = (index, outside) => {
    const theta = 180 * radians * index / half;
    const s = Math.sin(theta);
    return [u + (outside ? -radius * s : -.010 * s + .016 * s * s), v + radius * Math.cos(theta)];
  };
  return [
    ...Array.from({ length: half + 1 }, (_, index) => curve(index, true)),
    ...Array.from({ length: half - 1 }, (_, index) => curve(half - index - 1, false)),
  ];
}

