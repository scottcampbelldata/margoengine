// Writes examples/all-entries/entries.ts: one `export * as` line for every public entry of every package, read from the
// packages' exports maps, so `npm run check:examples-types` (project `all-entries`) type-checks every entry in one
// program with the library declarations checked too. Two packages whose declarations fight (a global declared twice,
// an entry whose types name a file that is not built, a type that only resolves in one package's own build) fail here,
// where no single package's own type check can see it. `npm run api:update` rewrites the file with the API reports;
// `npm run api:check` and tests/all-entries.test.js fail when it is stale.
//   node scripts/generate-all-entries.mjs          rewrite the file
//   node scripts/generate-all-entries.mjs --check  exit 1 when the file is stale
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
export const OUTPUT = 'examples/all-entries/entries.ts';

/**
 * Entries left out, each with its reason; the list must shrink to empty. Sciviz is still being built on the dev PC
 * (work list 5: batches 175, 176 and 178), so its entries and the kit entries that re-export it join when those are done.
 */
export const PENDING = [{ match: /(^@margoengine\/sciviz(\/|$))|(\/sciviz(\/|$))/, reason: 'sciviz batches 175, 176, 178' }];

/** Every public entry: [{ specifier, pkg }], packages by folder name, entries in exports map order. */
export function allEntries(dir = root) {
  const list = [];
  for (const folder of readdirSync(join(dir, 'packages')).sort()) {
    const file = join(dir, 'packages', folder, 'package.json');
    if (!existsSync(file)) continue;
    const manifest = JSON.parse(readFileSync(file, 'utf8'));
    if (manifest.private) continue;
    for (const key of Object.keys(manifest.exports ?? {})) {
      if (key.includes('*') || !/^\.(\/|$)/.test(key)) continue;
      const specifier = manifest.name + key.slice(1);
      if (PENDING.some(({ match }) => match.test(specifier))) continue;
      list.push({ specifier, pkg: manifest.name });
    }
  }
  return list;
}

/** The generated file's text. */
export function entriesSource(dir = root) {
  const used = new Set(),
    lines = allEntries(dir).map(({ specifier }) => {
      let name = `e_${specifier.replace(/^@/, '').replace(/[^A-Za-z0-9]/g, '_')}`;
      for (let i = 2; used.has(name); i++) name = `${name}_${i}`;
      used.add(name);
      return `export * as ${name} from '${specifier}';`;
    });
  return [
    '// Generated by scripts/generate-all-entries.mjs from the packages\' exports maps. Do not edit: run the script.',
    `// ${lines.length} public entries; left out until done: ${PENDING.map((p) => p.reason).join('; ')}.`,
    ...lines,
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const path = join(root, OUTPUT),
    want = entriesSource();
  if (process.argv.includes('--check')) {
    const have = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== want) {
      console.error(`${OUTPUT} is stale: run node scripts/generate-all-entries.mjs`);
      process.exit(1);
    }
  } else writeFileSync(path, want);
}
