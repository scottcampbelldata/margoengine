import { mkdirSync, readFileSync, readdirSync, writeFileSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { C2, commonC2, coveringArray, implementedC2, pairCoverage } from './support/composition-contracts.mjs';
import { exitOnHelp } from './support/help.mjs';

exitOnHelp(
  'node scripts/generate-composition.mjs [--check]\nGenerate C2 scenes or check committed output without writing.',
);

const folder = resolve(import.meta.dirname, '../tests/composition');
const check = process.argv.includes('--check');
const adapters = {
  post: 'FXAA',
  taa: 'TAA',
  dof: 'DOF',
  tonemap: 'Tonemap',
  oit: 'OIT, addMesh',
  pixel: 'LayerCompositor',
  creative: 'GPUParticles',
  scenery: 'Moon',
  'voxel-pathtracer': 'VoxelPathTracer',
  water: 'Water',
  sky: 'Sky',
  vfx: 'VFX',
  sprites: 'SpriteLayer',
  splats: 'Splats',
  lighting2d: 'Lighting2D',
  xr: 'XR, createXREngine',
  shadows: 'Shadows',
  clustered: 'Clustered',
  toon: 'Toon',
  transitions: 'Transitions',
  lines: 'Lines, Line',
  points: 'PointsPlugin, PointCloud',
  labels: 'LabelRenderer',
  text: 'TextRenderer, Text',
};
const rows = coveringArray(implementedC2).map((members, i) => ({
  id: `c2-${String(i + 1).padStart(3, '0')}`,
  members,
}));
const files = new Map();
for (const { id, members } of rows) {
  files.set(
    `${id}.html`,
    `<!doctype html>\n<meta charset="utf-8"><title>${id} render-pass composition</title>\n<script type="module" src="./${id}.ts"></script>\n`,
  );
  const imports = members
    .map((m) =>
      m === 'oit'
        ? "import { OIT } from '@margoengine/oit';\nimport { addMesh } from '@margoengine/oit/meshes';"
        : `import { ${adapters[m]} } from '@margoengine/${m === 'creative' ? 'creative/particles' : m === 'scenery' ? 'scenery/moon' : m}';`,
    )
    .join('\n');
  files.set(
    `${id}.ts`,
    `// Generated by scripts/generate-composition.mjs.\n${imports}\nimport { expose } from './harness.ts';\nexpose(${JSON.stringify({ id, members })}, { ${members.map((m) => `${JSON.stringify(m)}: ${adapters[m].includes(',') ? `{ ${adapters[m]} }` : adapters[m]}`).join(', ')} });\n`,
  );
}
files.set(
  'generated.json',
  `${JSON.stringify(
    {
      contract: 'C2',
      target: C2,
      implemented: implementedC2,
      common: commonC2,
      coverage: pairCoverage(
        C2,
        rows.map((r) => r.members),
      ),
      rows,
    },
    null,
    2,
  )}\n`,
);
mkdirSync(folder, { recursive: true });
for (const name of readdirSync(folder).filter((name) => /^c2-\d+\.(html|ts)$/.test(name) && !files.has(name))) {
  if (check) throw new Error(`Stale generated scene ${name}`);
  unlinkSync(resolve(folder, name));
}
for (const [name, body] of files) {
  const formatted = name.endsWith('.ts')
    ? execFileSync(
        process.execPath,
        [
          resolve(import.meta.dirname, '../node_modules/@biomejs/biome/bin/biome'),
          'format',
          '--stdin-file-path',
          `tests/composition/${name}`,
        ],
        { input: body, encoding: 'utf8', timeout: 30_000 },
      )
    : body;
  if (check) {
    if (readFileSync(resolve(folder, name), 'utf8').replaceAll('\r\n', '\n') !== formatted.replaceAll('\r\n', '\n'))
      throw new Error(`Regenerate tests/composition/${name}`);
  } else writeFileSync(resolve(folder, name), formatted);
}
console.log(
  `C2: ${rows.length} scenes, ${
    pairCoverage(
      C2,
      rows.map((r) => r.members),
    ).covered
  }/276 positive pairs`,
);
