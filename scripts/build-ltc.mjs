// Regenerates packages/clustered/src/ltc.ts, the LTC lookup table of @margoengine/clustered/area, from three.js's copy of the
// GGX fit by Heitz, Dupuy, Hill and Neubelt (2016, github.com/selfshadow/ltc_code), three/examples/jsm/lights/
// RectAreaLightTexturesLib.js (MIT). Six float16 values per cell: the inverse matrix's four free entries (LTC_MAT_1) and
// the magnitude and Fresnel terms (LTC_MAT_2 .xy). Each value plane is coded with a 2D gradient predictor and zigzag
// varints, so the bundle's gzip sees small, repetitive bytes. Smaller sizes resample the 64x64 fit bilinearly.
// 32x32 ships (~5.5 kB gzip; 64x64 is ~18 kB): against brute-force GGX it is as accurate as 64x64 everywhere measured
// (packages/clustered/test/area.test.js), and at grazing glossy views, where the fit itself is weakest, no worse.
// Run: node scripts/build-ltc.mjs [size=32]
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const size = +(process.argv[2] ?? 32);
if (!Number.isInteger(size) || size < 2 || size > 64) throw new RangeError('size must be 2-64');
const source = readFileSync(resolve(import.meta.dirname, '../node_modules/three/examples/jsm/lights/RectAreaLightTexturesLib.js'), 'utf8');
const table = name => JSON.parse(source.match(new RegExp(`const ${name} = (\\[[^\\]]+\\])`))[1].replace(/-\s+/g, '-'));
const m1 = table('LTC_MAT_1'), m2 = table('LTC_MAT_2');
if (m1.length !== 64 * 64 * 4 || m2.length !== 64 * 64 * 4) throw new Error('Unexpected three.js LTC table layout');
const f32 = new Float32Array(1), u32 = new Uint32Array(f32.buffer);
// Round-to-nearest-even float16 bits of a float (the tables hold no infinities or NaN).
function float16(value) {
  f32[0] = value; const bits = u32[0], sign = (bits >>> 16) & 0x8000, exponent = ((bits >>> 23) & 0xff) - 112, mantissa = bits & 0x7fffff;
  if (exponent <= 0) {if (exponent < -10) return sign; const m = mantissa | 0x800000, shift = 14 - exponent, rest = m & ((1 << shift) - 1), halfway = 1 << (shift - 1);
    let r = m >>> shift; if (rest > halfway || rest === halfway && r & 1) r++; return sign | r;}
  let r = (exponent << 10) | (mantissa >>> 13); const rest = mantissa & 0x1fff; if (rest > 0x1000 || rest === 0x1000 && r & 1) r++; return sign | r;
}
const bytes = [];
for (let k = 0; k < 6; k++) {
  const q = [];
  const at = (x, y) => {const i = y * 64 + x; return k < 4 ? m1[i * 4 + k] : m2[i * 4 + k - 4];};
  // Smaller tables resample bilinearly at the same parameters (cell i at i/(size-1)).
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const sx = x * 63 / (size - 1), sy = y * 63 / (size - 1), x0 = Math.floor(sx), y0 = Math.floor(sy), x1 = Math.min(x0 + 1, 63), y1 = Math.min(y0 + 1, 63), fx = sx - x0, fy = sy - y0;
    q.push(float16((at(x0, y0) * (1 - fx) + at(x1, y0) * fx) * (1 - fy) + (at(x0, y1) * (1 - fx) + at(x1, y1) * fx) * fy));
  }
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const left = x ? q[y * size + x - 1] : 0, up = y ? q[(y - 1) * size + x] : 0, corner = x && y ? q[(y - 1) * size + x - 1] : 0;
    const d = q[y * size + x] - (x && y ? left + up - corner : x ? left : up);
    let z = d < 0 ? -2 * d - 1 : 2 * d;
    do {const b = z & 0x7f; z = Math.floor(z / 128); bytes.push(z ? b | 0x80 : b);} while (z);
  }
}
const out = resolve(import.meta.dirname, '../packages/clustered/src/ltc.ts');
writeFileSync(out, `// Generated by scripts/build-ltc.mjs (do not edit): the GGX LTC fit of Heitz, Dupuy, Hill and Neubelt 2016
// (github.com/selfshadow/ltc_code), as shipped in three.js r186 RectAreaLightTexturesLib (MIT), ${size}x${size} cells.
/** Cells per side of the LTC table: columns are perceptual roughness 0..1, rows sqrt(1 - n.v) 0..1. */
export const ltcSize = ${size};
const data = '${Buffer.from(bytes).toString('base64')}';
/** Float16 bits, six per cell (row-major): the inverse matrix's columns (x, 0, y), (0, 1, 0), (z, 0, w) as x, y, z, w, then magnitude and Fresnel. */
export function ltcTable(): Uint16Array {
  const bytes = Uint8Array.from(atob(data), c => c.charCodeAt(0)), cells = ltcSize * ltcSize, out = new Uint16Array(cells * 6);
  let at = 0;
  for (let k = 0; k < 6; k++) for (let i = 0; i < cells; i++) {
    let z = 0, scale = 1, b: number;
    do {b = bytes[at++]; z += (b & 127) * scale; scale *= 128;} while (b & 128);
    const x = i % ltcSize, left = x ? out[(i - 1) * 6 + k] : 0, up = i >= ltcSize ? out[(i - ltcSize) * 6 + k] : 0;
    const corner = x && i >= ltcSize ? out[(i - ltcSize - 1) * 6 + k] : 0;
    out[i * 6 + k] = (z & 1 ? -(z + 1) / 2 : z / 2) + (x && i >= ltcSize ? left + up - corner : x ? left : up);
  }
  return out;
}
`);
console.log(`wrote ${out}: ${size}x${size}, ${bytes.length} bytes coded`);
