// Codemod: the Stage class lost its optional-package methods (2026-10-27). Each feature is now an entry that takes the
// stage, so an app bundles only what it imports and webpack/Turbopack never meet an uninstalled optional peer:
//   await stage.load('a.glb')          -> await addGLTF(stage, 'a.glb')         @margoengine/stage/gltf
//   await stage.load('a.step', opts)   -> await addCAD(stage, 'a.step', opts)   @margoengine/stage/cad (stl, obj, step, iges)
//   await stage.sky(o)                 -> await addSky(stage, o)                @margoengine/stage/sky
//   await stage.particles(o)           -> await addParticles(stage, o)          @margoengine/stage/particles
//   await stage.effects(o)             -> await addEffects(stage, o)            @margoengine/stage/effects
//   await stage.environment(url, o)    -> await addEnvironment(stage, url, o)   @margoengine/stage/environment
//   await stage.shadows(o)             -> await addShadows(stage, o)            @margoengine/stage/shadows
//   await stage.gltf() / machinery() / creative() / scenery() -> await import('@margoengine/<package>')
// In a file (or Markdown code fence) that imports from 'margoengine', the entries are 'margoengine/stage/<entry>'.
//
// Usage: node scripts/codemod-stage-loaders.mjs [--check] [paths...]
//   No paths: every tracked .ts/.tsx/.js/.jsx/.mjs/.cjs/.md file except generated records and history.
//   Rewrites .js/.ts sources and the code fences of Markdown files in place; idempotent (a second run changes nothing).
//   Prints every call it could not rewrite (a URL whose format it cannot tell, a call with no import to extend) with
//   its file and line, and exits 1 when there are any, or with --check when a file would change. Prose mentions in
//   Markdown (`app.load()` inside a sentence) are listed, not changed.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { extname } from 'node:path';

const PLUGINS = {
  sky: ['addSky', 'sky'],
  particles: ['addParticles', 'particles'],
  effects: ['addEffects', 'effects'],
  environment: ['addEnvironment', 'environment'],
  shadows: ['addShadows', 'shadows'],
};
const PACKS = ['gltf', 'machinery', 'creative', 'scenery'];
const GLTF = new Set(['gltf', 'glb']),
  CAD = new Set(['stl', 'obj', 'step', 'stp', 'iges', 'igs']);
const CODE = new Set(['.ts', '.tsx', '.js', '.mjs', '.cjs', '.jsx']);
// Generated or historical text: regenerated by its own script, or a record of what was true at the time.
const SKIP = [
  /^api\//,
  /^site\/llms/,
  /(^|\/)dist\//,
  /(^|\/)node_modules\//,
  /^CHANGELOG\.md$/,
  /^docs\/HANDOFF\.md$/,
  /^docs\/whitepaper\//,
  /^docs\/perf-history/,
  /^scripts\/codemod-stage-loaders\.mjs$/,
  /^tests\/codemod-stage-loaders\.test\.js$/,
  /^private\//,
];

/** Index just past the `)` closing the `(` at `open`, skipping strings, templates and comments; -1 if unbalanced. */
function closing(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"' || c === "'" || c === '`') {
      for (i++; i < text.length && text[i] !== c; i++) if (text[i] === '\\') i++;
      continue;
    }
    if (c === '/' && text[i + 1] === '/') {
      i = text.indexOf('\n', i);
      if (i < 0) return -1;
      continue;
    }
    if (c === '/' && text[i + 1] === '*') {
      i = text.indexOf('*/', i);
      if (i < 0) return -1;
      i++;
      continue;
    }
    if (c === '(' || c === '[' || c === '{') depth++;
    else if (c === ')' || c === ']' || c === '}') if (--depth === 0) return i + 1;
  }
  return -1;
}

/** The receivers that hold a Stage in `text`: `stage`, `app`, and names bound to createStage or new Stage. */
function receivers(text) {
  const names = new Set(['stage', 'app']);
  for (const match of text.matchAll(/(?:const|let|var)\s+([\w$]+)\s*=\s*(?:await\s+)?(?:[\w$.]*\.)?createStage\(/g))
    names.add(match[1]);
  for (const match of text.matchAll(/(?:const|let|var)\s+([\w$]+)\s*=\s*new\s+(?:[\w$]+\.)?(?:Stage|StageFacade)\(/g))
    names.add(match[1]);
  return names;
}

const lineOf = (text, index) => text.slice(0, index).split('\n').length;

/**
 * What each character of a source is: 0 code, 1 comment or quoted string (left alone), 2 inside a template literal
 * (browser-test code evaluated from a string: rewritten, but its import is added by hand).
 */
function regions(text) {
  const kind = new Uint8Array(text.length);
  const stack = [];
  for (let i = 0; i < text.length; i++) {
    const c = text[i],
      inTemplate = stack.length > 0 && stack.at(-1) === 'template';
    if (inTemplate) {
      kind[i] = 2;
      if (c === '\\') {
        kind[++i] = 2;
      } else if (c === '`') stack.pop();
      else if (c === '$' && text[i + 1] === '{') {
        kind[++i] = 2;
        stack.push(0);
      }
      continue;
    }
    const nested = stack.length > 0;
    if (nested) {
      kind[i] = 2;
      if (c === '{') stack[stack.length - 1]++;
      else if (c === '}') {
        if (stack.at(-1) === 0) {
          stack.pop();
          continue;
        }
        stack[stack.length - 1]--;
      }
    }
    if (c === '`') {
      stack.push('template');
      kind[i] = 2;
    } else if (c === '/' && text[i + 1] === '/') {
      const end = text.indexOf('\n', i);
      const stop = end < 0 ? text.length : end;
      kind.fill(1, i, stop);
      i = stop - 1;
    } else if (c === '/' && text[i + 1] === '*') {
      const end = text.indexOf('*/', i + 2);
      const stop = end < 0 ? text.length : end + 2;
      kind.fill(1, i, stop);
      i = stop - 1;
    } else if (c === '"' || c === "'") {
      let j = i + 1;
      for (; j < text.length && text[j] !== c && text[j] !== '\n'; j++) if (text[j] === '\\') j++;
      kind.fill(1, i, j + 1);
      i = j;
    } else if (
      c === '/' &&
      /(?:^|[=(,:[!&|?{};+\-*%<>~^]|\breturn|\btypeof)\s*$/.test(text.slice(Math.max(0, i - 12), i))
    ) {
      // A regular expression literal: its quotes and slashes are not strings or comments.
      let j = i + 1,
        inClass = false;
      for (; j < text.length && text[j] !== '\n'; j++) {
        if (text[j] === '\\') j++;
        else if (text[j] === '[') inClass = true;
        else if (text[j] === ']') inClass = false;
        else if (text[j] === '/' && !inClass) break;
      }
      if (text[j] === '/') {
        kind.fill(1, i, j + 1);
        i = j;
      }
    }
  }
  // Functions a test hands to the browser (`page.evaluate(async () => ...)`) run in the page, not in this module.
  for (const match of text.matchAll(/\.(?:evaluate|evaluateHandle|waitForFunction|addInitScript|\$eval|\$\$eval)\(/g)) {
    const open = match.index + match[0].length - 1,
      end = closing(text, open);
    if (end > 0) for (let i = open; i < end; i++) if (kind[i] === 0) kind[i] = 2;
  }
  return kind;
}

/** Picks addGLTF or addCAD for a `load(args)` call from its URL literal or `format` option; null if it cannot tell. */
function loader(args) {
  const literal = /^\s*(['"`])([^'"`]*)\1/.exec(args);
  const format = /format:\s*(['"])(\w+)\1/.exec(args)?.[2];
  const extension = literal?.[2].split(/[?#]/)[0].toLowerCase().split('.').at(-1);
  for (const kind of [format, extension]) {
    if (GLTF.has(kind)) return 'gltf';
    if (CAD.has(kind)) return 'cad';
  }
  return null;
}

/** Rewrites one JavaScript or TypeScript source. Returns the text, the entries it needs and unresolved calls. */
export function transform(text) {
  const needs = new Map(),
    problems = [];
  const names = [...receivers(text)].map((name) => name.replace(/\$/g, '\\$'));
  const pattern = new RegExp(
    `(?<![\\w$])((?:[\\w$]+\\.)*(?:${names.join('|')}))\\.(load|${Object.keys(PLUGINS).join('|')}|${PACKS.join('|')})\\(`,
    'g',
  );
  const kind = regions(text);
  let output = '',
    last = 0;
  for (const match of text.matchAll(pattern)) {
    if (match.index < last || kind[match.index] === 1) continue;
    const templated = kind[match.index] === 2,
      need = (name, entry) => {
        if (!templated) needs.set(name, entry);
        else
          problems.push({
            line: lineOf(text, match.index),
            call: `${name} used in code inside a template string: import it from @margoengine/stage/${entry} there`,
          });
      };
    const [whole, receiver, method] = match,
      open = match.index + whole.length - 1,
      end = closing(text, open);
    if (receiver.endsWith('engine') || receiver.includes('engine.') || end < 0) continue;
    const args = text.slice(open + 1, end - 1);
    let replacement;
    if (method === 'load') {
      const format = loader(args);
      if (!format) {
        problems.push({ line: lineOf(text, match.index), call: text.slice(match.index, end) });
        continue;
      }
      const name = format === 'gltf' ? 'addGLTF' : 'addCAD';
      // addGLTF reads the format itself; its options have no `format`.
      const rest =
        format === 'gltf'
          ? args
              .replace(/\{\s*format:\s*(['"])(gltf|glb)\1\s*\}/, '{}')
              .replace(/format:\s*(['"])(gltf|glb)\1\s*,\s*/, '')
              .replace(/,\s*\{\s*\}\s*$/, '')
          : args;
      need(name, format);
      replacement = `${name}(${receiver}, ${rest.trim()})`;
    } else if (method in PLUGINS) {
      const [name, entry] = PLUGINS[method];
      need(name, entry);
      replacement = args.trim() ? `${name}(${receiver}, ${args.trim()})` : `${name}(${receiver})`;
    } else {
      if (args.trim()) continue;
      replacement = `import('\0${method}')`;
    }
    output += text.slice(last, match.index) + replacement;
    last = end;
  }
  output += text.slice(last);
  // `(await stage.machinery()) as typeof import('x')` became `(await import('x')) as typeof import('x')`: drop the cast.
  output = output.replace(/\((await import\('\0(\w+)'\))\)\s+as\s+typeof\s+import\(['"][^'"]+['"]\)/g, '$1');
  return { text: output, needs, problems };
}

/** The import base for `text`: 'margoengine' when it imports the umbrella, else '@margoengine/stage'. */
function base(text) {
  return /from\s+['"]margoengine(?:\/[^'"]*)?['"]|import\(\s*['"]margoengine['"]\s*\)/.test(text)
    ? 'margoengine'
    : '@margoengine/stage';
}

/** Adds `import { name } from '<base>/stage/<entry>'` for each need, merging into an existing import of that entry. */
function addImports(text, needs) {
  const root = base(text),
    packs = root === 'margoengine' ? 'margoengine' : '@margoengine';
  text = text.replace(/import\('\0(\w+)'\)/g, (_, pack) => `import('${packs}/${pack}')`);
  if (!needs.size) return { text, ok: true };
  let ok = true;
  for (const [name, entry] of needs) {
    const specifier = `${root === 'margoengine' ? 'margoengine/stage' : '@margoengine/stage'}/${entry}`,
      existing = new RegExp(`^import\\s*\\{([^}]*)\\}\\s*from\\s*(['"])${specifier}\\2;?`, 'm').exec(text);
    if (existing) {
      if (!new RegExp(`(?<![\\w$])${name}(?![\\w$])`).test(existing[1])) {
        const names = [
          ...existing[1]
            .split(',')
            .map((n) => n.trim())
            .filter(Boolean),
          name,
        ].sort();
        text = text.replace(
          existing[0],
          `import { ${names.join(', ')} } from ${existing[2]}${specifier}${existing[2]};`,
        );
      }
      continue;
    }
    const anchor = [...text.matchAll(/^import\s[^;]*?from\s+['"][^'"]+['"];?[^\S\n]*$/gm)];
    const quote = /from\s+(['"])/.exec(anchor.at(-1)?.[0] ?? '')?.[1] ?? "'";
    const statement = `import { ${name} } from ${quote}${specifier}${quote};`;
    const after =
      anchor.filter((m) => /from\s+['"](margoengine|@margoengine\/stage)['"]/.test(m[0])).at(-1) ?? anchor.at(-1);
    if (!after) {
      ok = false;
      continue;
    }
    const at = after.index + after[0].length;
    text = `${text.slice(0, at)}\n${statement}${text.slice(at)}`;
  }
  return { text, ok };
}

/** Rewrites a code file or one Markdown fence; returns the new text and problems (with fence-relative lines). */
export function rewriteCode(text) {
  const result = transform(text),
    imported = addImports(result.text, result.needs);
  const problems = [...result.problems];
  if (!imported.ok)
    problems.push({ line: 1, call: `needs ${[...result.needs.keys()].join(', ')} but has no import to extend` });
  return { text: imported.text, problems };
}

const hasImport = (code) => /^\s*import\s[^;]*?from\s+['"]/m.test(code);

/**
 * Rewrites the ```js/ts fences of a Markdown file; lists prose mentions it leaves alone. A fence without imports
 * continues the setup of the fence before it (as the README type-check reads them), so its imports go there.
 */
export function rewriteMarkdown(text) {
  const problems = [],
    prose = [];
  const fence = /^(```|~~~)(\w*)[^\n]*\n([\s\S]*?)^\1[^\S\n]*$/gm;
  const blocks = [];
  for (const match of text.matchAll(fence)) {
    const [whole, , language, body] = match,
      start = match.index + whole.indexOf('\n') + 1;
    blocks.push({ start, body, code: /^(js|javascript|ts|typescript|jsx|tsx|mjs)?$/.test(language), text: body });
  }
  let owner = null;
  for (const block of blocks) {
    if (!block.code) continue;
    if (hasImport(block.body)) owner = block;
    const result = transform(block.body);
    for (const problem of result.problems)
      problems.push({ line: lineOf(text, block.start) + problem.line - 1, call: problem.call });
    const target = hasImport(block.body) || !owner ? block : owner;
    if (target === block) {
      const imported = addImports(result.text, result.needs);
      block.text = imported.text;
      if (!imported.ok)
        problems.push({
          line: lineOf(text, block.start),
          call: `needs ${[...result.needs.keys()].join(', ')} but has no import`,
        });
    } else {
      // The packs' import() specifiers follow the setup block's root ('margoengine' or '@margoengine/...').
      block.text = addImports(
        `${owner.text.match(/^import\s[^\n]*$/gm)?.join('\n') ?? ''}\n\0\n${result.text}`,
        new Map(),
      )
        .text.split('\n\0\n')
        .slice(1)
        .join('\n\0\n');
      owner.text = addImports(owner.text, result.needs).text;
    }
  }
  let output = '',
    last = 0;
  for (const block of blocks) {
    output += text.slice(last, block.start) + block.text;
    last = block.start + block.body.length;
  }
  output += text.slice(last);
  const stripped = output.replace(fence, (block) => block.replace(/[^\n]/g, ' '));
  for (const match of stripped.matchAll(
    /(?<![\w$])(?:app|stage)\.(load|sky|particles|effects|environment|shadows|gltf|machinery|creative|scenery)\(/g,
  ))
    prose.push({ line: lineOf(stripped, match.index), call: match[0] });
  return { text: output, problems, prose };
}

function files(paths) {
  const listed = paths.length
    ? paths
    : execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8' }).split('\0').filter(Boolean);
  return listed
    .map((file) => file.replace(/\\/g, '/'))
    .filter((file) => (CODE.has(extname(file)) || extname(file) === '.md') && !SKIP.some((re) => re.test(file)));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop())) {
  const check = process.argv.includes('--check'),
    paths = process.argv.slice(2).filter((arg) => !arg.startsWith('--'));
  let changed = 0,
    unresolved = 0;
  for (const file of files(paths)) {
    let source;
    try {
      source = readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    if (!/\.(load|sky|particles|effects|environment|shadows|gltf|machinery|creative|scenery)\(/.test(source)) continue;
    const crlf = source.includes('\r\n'),
      text = crlf ? source.replace(/\r\n/g, '\n') : source;
    const result = extname(file) === '.md' ? rewriteMarkdown(text) : rewriteCode(text);
    for (const problem of result.problems) {
      unresolved++;
      console.log(`${file}:${problem.line}: rewrite by hand: ${problem.call.split('\n')[0]}`);
    }
    for (const mention of result.prose ?? []) console.log(`${file}:${mention.line}: prose mentions ${mention.call}`);
    if (result.text !== text) {
      changed++;
      if (check) console.log(`${file}: would change`);
      else writeFileSync(file, crlf ? result.text.replace(/\n/g, '\r\n') : result.text);
    }
  }
  console.log(`${changed} file(s) ${check ? 'to change' : 'changed'}, ${unresolved} call(s) to rewrite by hand`);
  process.exit(unresolved || (check && changed) ? 1 : 0);
}
