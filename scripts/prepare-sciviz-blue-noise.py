"""Clean-room periodic void-and-cluster ranking, Ulichney (1993), sigma 1.5.

This offline asset generator uses NumPy, never the browser runtime. No external
mask or implementation is used. Every threshold of the resulting permutation
retains the relaxed spatial distribution.
"""
from pathlib import Path
import numpy as np

n = 32
rng = np.random.Generator(np.random.PCG64(17304))
y, x = np.mgrid[:n, :n]
kernel = np.exp(-(np.minimum(x, n-x)**2 + np.minimum(y, n-y)**2)/(2*1.5**2))
pattern = np.zeros(n*n, dtype=bool)
pattern[rng.permutation(n*n)[:n*n//2]] = True
pattern = pattern.reshape(n, n)

def density(p):
    return np.fft.ifft2(np.fft.fft2(p)*np.fft.fft2(kernel)).real

def change(d, i, sign):
    d += sign*np.roll(kernel, (i//n, i % n), axis=(0, 1))

d = density(pattern)
for iteration in range(10000):
    cluster = int(np.argmax(np.where(pattern, d, -np.inf)))
    pattern.flat[cluster] = False
    change(d, cluster, -1)
    void = int(np.argmin(np.where(pattern, np.inf, d)))
    pattern.flat[void] = True
    change(d, void, 1)
    if cluster == void:
        break
else:
    raise RuntimeError('Void-and-cluster relaxation did not stabilize')

initial = pattern.copy()
ranks = np.empty((n,n), dtype=np.int32)
for rank in range(n*n//2-1, -1, -1):
    cluster = int(np.argmax(np.where(pattern, d, -np.inf)))
    ranks.flat[cluster] = rank
    pattern.flat[cluster] = False
    change(d, cluster, -1)
pattern = initial.copy()
d = density(pattern)
for rank in range(n*n//2, n*n):
    void = int(np.argmin(np.where(pattern, np.inf, d)))
    ranks.flat[void] = rank
    pattern.flat[void] = True
    change(d, void, 1)

assert sorted(ranks.flat) == list(range(n*n))
out = '// Generated by scripts/prepare-sciviz-blue-noise.py, clean-room Ulichney (1993).\n'
out += 'export const blueNoiseRanks = new Uint16Array([\n'
out += '\n'.join('  '+','.join(map(str, row))+',' for row in ranks)+'\n]);\n'
Path('packages/sciviz/src/volume-blue-noise.ts').write_text(out)
print(f'{n}x{n} mask, {iteration+1} relaxation swaps, permutation 0..{n*n-1}')
