/** True for a margoengine entry that only re-exports another package's entry (not the root, not a kit). */
export const isUmbrellaAlias = (name, subpath) =>
  (name === UMBRELLA && subpath !== '.' && !(subpath.slice(2) in KITS)) || (isInstallKit(name) && subpath !== '.');

const manifests = (root) =>
  readdirSync(join(root, 'packages'))
    .filter((dir) => dir !== UMBRELLA && !(dir in KIT_MEMBERS) && existsSync(join(root, 'packages', dir, 'package.json')))
    .sort()
    .map((dir) => ({ dir, manifest: JSON.parse(readFileSync(join(root, 'packages', dir, 'package.json'), 'utf8')) }));

/** The alias entries: `margoengine/<package>[/<entry>]` -> the `@margoengine/...` entry it re-exports. */
export function umbrellaEntries(root = repository) {
  const entries = [];
  for (const { manifest } of manifests(root)) {
    const name = manifest.name.slice('@margoengine/'.length);
    for (const key of Object.keys(manifest.exports ?? {})) {
      // The stage's root is the root entry, `margoengine` itself; its feature entries are `margoengine/stage/<entry>`.
      if (manifest.name === '@margoengine/stage' && key === '.') continue;
      const file = key === '.' ? name : `${name}/${key.slice(2)}`;
      entries.push({
        subpath: `./${file}`,
        file,
        source: key === '.' ? manifest.name : `${manifest.name}/${key.slice(2)}`,
      });
    }
  }
  return entries;
}

/**
 * A browser import map for every entry of margoengine and every @margoengine/* package, from `base` (a CDN serving npm
 * packages as files, `<base><name>@<version>/<path>`). The build writes it to margoengine's dist/importmap.json, so a
 * page without a bundler can copy it from the CDN; see docs/guides/imports.md.
 */
export function importMap(root = repository, base = 'https://cdn.jsdelivr.net/npm/') {
  const imports = {};
  const all = [
    ...manifests(root).map(({ manifest }) => manifest),
    JSON.parse(readFileSync(join(root, 'packages', UMBRELLA, 'package.json'), 'utf8')),
  ];
  for (const manifest of all)
    for (const [key, target] of Object.entries(manifest.exports ?? {}))
      imports[manifest.name + key.slice(1)] = `${base}${manifest.name}@${manifest.version}/${target.import.slice(2)}`;
  return { imports };
}

/**
 * The @margoengine/react subpaths margoengine/react leaves out, each still its own margoengine/react/<name>. Physics
 * needs Rapier, a third-party library the app installs itself. The others reach gltf/pbr and so the Draco and Basis
 * decoders: Vite copies a module's `new URL(..., import.meta.url)` file when it reads the module, before tree-shaking,
 * so re-exporting them here put the Wasm in the build of every page, whatever the page used. The JSX runtimes are what
 * a compiler imports for `jsxImportSource`, not bindings, and their `Fragment` would clash with React's.
 */
export const REACT_SEPARATE = [
  'physics',
  'gltf',
  'fbx',
  'animation',
  'materials',
  'textures',
  'jsx-runtime',
  'jsx-dev-runtime',
].map((name) => `@margoengine/react/${name}`);

/**
 * The @margoengine entries one alias re-exports: its own, except margoengine/react, the one install, which has every
 * package and so re-exports the React root and each @margoengine/react/<package> subpath (which @margoengine/react keeps
 * apart so it builds without optional peers), but for REACT_SEPARATE.
 */
export function aliasSources(entries, source) {
  return source === '@margoengine/react'
    ? entries
        .filter((entry) => entry.source.startsWith('@margoengine/react') && !REACT_SEPARATE.includes(entry.source))
        .map((entry) => entry.source)
    : [source];
}

/**
 * margoengine/importmap, a page without a bundler served from the app's own origin: the published dist/importmap.json
 * points at jsDelivr, and this module points the same entries at a local base instead (the usual `/node_modules/`),
 * keeping all of them or only the entries a page reaches. Pure string work, so it runs in a page, a worker and Node.
 */
export const IMPORT_MAP_SOURCE = `${banner}// margoengine/importmap: the import map for a local base URL (docs/guides/imports.md, "No bundler").
const CDN = /^https:\\/\\/cdn\\.jsdelivr\\.net\\/npm\\/((?:@[^/]+\\/)?[^@/]+)@[^/]+\\/(.+)$/;
const help = 'see https://margoengine.com/errors#import-map';

/** An import map: the bare specifier of every entry and the URL of its file. */
export interface ImportMap {
  imports: Record<string, string>;
}

export interface LocalImportMapOptions {
  /**
   * Keep only these entries: a specifier (\`margoengine/shadows\`), or a prefix ending in \`/\` (\`@margoengine/core/\`
   * keeps itself and its subpaths, and \`@margoengine/\` every package). Default: every entry.
   */
  only?: readonly string[];
}

/**
 * Points an import map of CDN URLs (margoengine's dist/importmap.json) at \`base\`, where an npm install of the same
 * packages is served as \`<base><package>/<path>\`: \`/node_modules/\` for a dev server that serves the project folder, or
 * an absolute URL. Entries that do not match the CDN layout are kept as they are.
 * @example
 * rebaseImportMap({imports: {margoengine: 'https://cdn.jsdelivr.net/npm/margoengine@1.0.0/dist/index.js'}}, '/node_modules/');
 * // {imports: {margoengine: '/node_modules/margoengine/dist/index.js'}}
 */
export function rebaseImportMap(map: ImportMap, base = '/node_modules/', options: LocalImportMapOptions = {}): ImportMap {
  if (typeof base !== 'string' || base === '') throw new TypeError(\`The import map base must be a non-empty string; \${help}\`);
  if (!map || typeof map.imports !== 'object' || map.imports === null)
    throw new TypeError(\`rebaseImportMap needs an import map with an "imports" object; \${help}\`);
  const root = base.endsWith('/') ? base : \`\${base}/\`,
    only = options.only,
    keep = (specifier: string) =>
      !only || only.some((name) => (name.endsWith('/') ? specifier.startsWith(name) || specifier === name.slice(0, -1) : specifier === name));
  const imports: Record<string, string> = {};
  for (const [specifier, url] of Object.entries(map.imports)) {
    if (!keep(specifier)) continue;
    const match = CDN.exec(url);
    imports[specifier] = match ? \`\${root}\${match[1]}/\${match[2]}\` : url;
  }
  if (only) {
    const missing = only.filter((name) => !Object.keys(imports).some((key) => (name.endsWith('/') ? key.startsWith(name) || key === name.slice(0, -1) : key === name)));
    if (missing.length) throw new RangeError(\`No import map entry for \${missing.join(', ')}; \${help}\`);
  }
  return { imports };
}

/**
 * The import map of this install for a page served from your own origin, from margoengine's own dist/importmap.json
 * (read with fetch in a page, from disk in Node).
 * @example
 * const map = await localImportMap('/node_modules/', {only: ['margoengine', 'margoengine/shadows']});
 * html = \`<script type="importmap">\${JSON.stringify(map)}</script>\`;
 */
export async function localImportMap(base = '/node_modules/', options: LocalImportMapOptions = {}): Promise<ImportMap> {
  const url = new URL('./importmap.json', import.meta.url);
  let text: string;
  if (url.protocol === 'file:') {
    const read = 'node:fs/promises';
    text = await ((await import(/* @vite-ignore */ read)) as {readFile(url: URL, encoding: 'utf8'): Promise<string>}).readFile(url, 'utf8');
  } else {
    const response = await fetch(url);
    if (!response.ok)
      throw Object.assign(new Error(\`Could not read \${url.href} (\${response.status}); serve margoengine/dist next to margoengine/importmap; \${help}\`), {
        name: 'MargoError',
        code: 'failed',
      });
    text = await response.text();
  }
  return rebaseImportMap(JSON.parse(text) as ImportMap, base, options);
}
`;

