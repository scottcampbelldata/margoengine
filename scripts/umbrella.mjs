// margoengine, the one-install package: every entry of every @margoengine/* package as margoengine/<package>[/<entry>]
// (margoengine/gltf, margoengine/controls/orbit, ...), and its root is the stage (@margoengine/stage). Generated from
// the packages' exports maps: `node scripts/umbrella.mjs` writes packages/margoengine/src/** and the exports,
// dependencies and optional third-party peers of packages/margoengine/package.json; `--check` fails when they are out
// of date (tests/umbrella.test.js). Each file is one `export * from` line, so an app still loads only what it imports.
