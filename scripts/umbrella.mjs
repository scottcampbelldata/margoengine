/** True for a margoengine entry that only re-exports another package's entry (not the root, not a kit). */
export const isUmbrellaAlias = (name, subpath) => name === UMBRELLA && subpath !== '.' && !(subpath.slice(2) in KITS);

const manifests = (root) =>
  readdirSync(join(root, 'packages'))
    .filter((dir) => dir !== UMBRELLA && existsSync(join(root, 'packages', dir, 'package.json')))
    .sort()
    .map((dir) => ({ dir, manifest: JSON.parse(readFileSync(join(root, 'packages', dir, 'package.json'), 'utf8')) }));

/** The alias entries: `margoengine/<package>[/<entry>]` -> the `@margoengine/...` entry it re-exports. */
export function umbrellaEntries(root = repository) {
  const entries = [];
  for (const { manifest } of manifests(root)) {
    const name = manifest.name.slice('@margoengine/'.length);
    for (const key of Object.keys(manifest.exports ?? {})) {
      // The stage's root is the root entry, `margoengine` itself; its feature entries are `margoengine/stage/<entry>`.
      if (manifest.name === '@margoengine/stage' && key === '.') continue;
      const file = key === '.' ? name : `${name}/${key.slice(2)}`;
      entries.push({
        subpath: `./${file}`,
        file,
        source: key === '.' ? manifest.name : `${manifest.name}/${key.slice(2)}`,
      });
    }
  }
  return entries;
}

/**
 * A browser import map for every entry of margoengine and every @margoengine/* package, from `base` (a CDN serving npm
 * packages as files, `<base><name>@<version>/<path>`). The build writes it to margoengine's dist/importmap.json, so a
 * page without a bundler can copy it from the CDN; see docs/guides/imports.md.
 */
export function importMap(root = repository, base = 'https://cdn.jsdelivr.net/npm/') {
  const imports = {};
  const all = [
    ...manifests(root).map(({ manifest }) => manifest),
    JSON.parse(readFileSync(join(root, 'packages', UMBRELLA, 'package.json'), 'utf8')),
  ];
  for (const manifest of all)
    for (const [key, target] of Object.entries(manifest.exports ?? {}))
      imports[manifest.name + key.slice(1)] = `${base}${manifest.name}@${manifest.version}/${target.import.slice(2)}`;
  return { imports };
}

/**
 * The @margoengine/react subpaths margoengine/react leaves out, each still its own margoengine/react/<name>. Physics
 * needs Rapier, a third-party library the app installs itself. The others reach gltf-pro and so the Draco and Basis
 * decoders: Vite copies a module's `new URL(..., import.meta.url)` file when it reads the module, before tree-shaking,
 * so re-exporting them here put the Wasm in the build of every page, whatever the page used. The JSX runtimes are what
 * a compiler imports for `jsxImportSource`, not bindings, and their `Fragment` would clash with React's.
 */
export const REACT_SEPARATE = [
  'physics',
  'gltf-pro',
  'fbx',
  'animation',
  'materials',
  'jsx-runtime',
  'jsx-dev-runtime',
].map((name) => `@margoengine/react/${name}`);

/**
 * The @margoengine entries one alias re-exports: its own, except margoengine/react, the one install, which has every
 * package and so re-exports the React root and each @margoengine/react/<package> subpath (which @margoengine/react keeps
 * apart so it builds without optional peers), but for REACT_SEPARATE.
 */
export function aliasSources(entries, source) {
  return source === '@margoengine/react'
    ? entries
        .filter((entry) => entry.source.startsWith('@margoengine/react') && !REACT_SEPARATE.includes(entry.source))
        .map((entry) => entry.source)
    : [source];
}

/** The files and package.json the generator writes, as {path: text}. */
export function umbrellaFiles(root = repository) {
  const files = {},
    exports = { '.': { types: './dist/index.d.ts', import: './dist/index.js' } };
  files['packages/margoengine/src/index.ts'] =
    `${banner}// \`margoengine\` is the stage: createStage, Stage, box, sphere and everything @margoengine/core exports.\nexport * from '@margoengine/stage';\n`;
  const entries = umbrellaEntries(root);
  for (const { subpath, file, source } of entries) {
    const all = aliasSources(entries, source);
    files[`packages/margoengine/src/${file}.ts`] =
      `${banner}${all.map((name) => `export * from '${name}';`).join('\n')}\n`;
    exports[subpath] = { types: `./dist/${file}.d.ts`, import: `./dist/${file}.js` };
  }
  for (const [kit, { about, from }] of Object.entries(KITS)) {
    const path = `packages/margoengine/src/${kit}.ts`;
    if (files[path]) throw new Error(`Kit margoengine/${kit} clashes with a package of that name; rename the kit`);
    const seen = new Set();
    const lines = from.map(([source, names]) => {
      for (const name of names) {
        if (seen.has(name)) throw new Error(`Kit margoengine/${kit} exports ${name} twice; keep one`);
        seen.add(name);
      }
      // Biome's layout: one line when it fits in 120 columns, else one name per line.
      const line = `export { ${names.join(', ')} } from '${source}';`;
      return line.length <= 120 ? line : `export {\n${names.map((name) => `  ${name},\n`).join('')}} from '${source}';`;
    });
    files[path] =
      `${banner}// margoengine/${kit}: ${about}. Contents and sizes: docs/guides/kits.md.\n${lines.join('\n')}\n`;
    exports[`./${kit}`] = { types: `./dist/${kit}.d.ts`, import: `./dist/${kit}.js` };
  }
  const packages = manifests(root),
    dependencies = Object.fromEntries(packages.map(({ manifest }) => [manifest.name, `^${manifest.version}`])),
    // Third-party libraries a package takes from the app stay optional peers: install them only to use that package.
    peers = {};
  for (const { manifest } of packages)
    for (const [name, range] of Object.entries(manifest.peerDependencies ?? {}))
      if (!name.startsWith('@margoengine/') && name !== UMBRELLA) peers[name] = range;
  const path = 'packages/margoengine/package.json',
    current = JSON.parse(readFileSync(join(root, path), 'utf8'));
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  const manifest = {
    ...current,
    license: 'Apache-2.0',
    files: [...new Set([...(current.files ?? ['dist']), 'NOTICE'])],
    sideEffects: false,
    exports,
    dependencies: sorted(dependencies),
    peerDependencies: sorted(peers),
    peerDependenciesMeta: sorted(Object.fromEntries(Object.keys(peers).map((name) => [name, { optional: true }]))),
  };
  files[path] = `${JSON.stringify(manifest, null, 2)}\n`;
  // The kits' contents in docs/guides/kits.md, between its markers.
  const guide = 'docs/guides/kits.md',
    text = readFileSync(join(root, guide), 'utf8').replace(/\r\n/g, '\n'),
    [before, rest] = text.split('<!-- kits:start -->\n'),
    after = rest.slice(rest.indexOf('<!-- kits:end -->'));
  const contents = Object.entries(KITS)
    .map(
      ([kit, { about, from }]) =>
        `### \`margoengine/${kit}\`\n\n${about}.\n\n| From | Names |\n| --- | --- |\n${from
          .map(
            ([source, names]) =>
              `| \`margoengine${source.slice('@margoengine'.length).replace('/stage', '')}\` | ${names.map((n) => `\`${n}\``).join(', ')} |`,
          )
          .join('\n')}\n`,
    )
    .join('\n');
  files[guide] = `${before}<!-- kits:start -->\n${contents}${after}`;
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check'),
    files = umbrellaFiles(),
    src = join(repository, 'packages/margoengine/src');
  const stale = Object.entries(files).filter(
    ([path, text]) =>
      !existsSync(join(repository, path)) ||
      readFileSync(join(repository, path), 'utf8').replace(/\r\n/g, '\n') !== text,
  );
  // Files left over from a removed package or entry.
  const generated = new Set(Object.keys(files));
  const extra = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (!generated.has(path.slice(repository.length + 1).replaceAll('\\', '/'))) extra.push(path);
    }
  };
  if (existsSync(src)) walk(src);
  if (check) {
    const problems = [...stale.map(([path]) => path), ...extra.map((path) => path.slice(repository.length + 1))];
    if (problems.length) {
      console.error(`margoengine is out of date (${problems.join(', ')}); run node scripts/umbrella.mjs`);
      process.exit(1);
    }
    console.log(`margoengine: ${Object.keys(files).length - 2} entries up to date`);
  } else {
    for (const path of extra) rmSync(path);
    for (const [path, text] of stale) {
      mkdirSync(dirname(join(repository, path)), { recursive: true });
      // Match the checkout's line endings (git normalizes them on commit).
      const crlf = readFileSync(join(repository, 'package.json'), 'utf8').includes('\r\n');
      writeFileSync(join(repository, path), crlf ? text.replace(/\n/g, '\r\n') : text);
    }
    console.log(`margoengine: ${Object.keys(files).length - 2} entries, ${stale.length} files written`);
  }
}
