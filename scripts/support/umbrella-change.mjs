// When a change to the margoengine umbrella (packages/margoengine) needs no full check:merge run (session rule 20).
// The umbrella is generated (scripts/umbrella.mjs): one `export * from` line per entry of every package. Adding or
// removing such an entry changes nothing in core, stage or the other packages, so it is not a reason for everything to
// run; the package that gained the entry is the real change. Anything else in the umbrella (a kit, a dependency, a
// peer, the tsconfig, an entry that re-exports something other than a package) stays a full run.
// Pure: file texts in, a yes or no out. check-merge.mjs reads the texts from git (changedUmbrellaReader).
import { execFileSync } from 'node:child_process';

const UMBRELLA_DIR = 'packages/margoengine/';
const BANNER = '// Generated by scripts/umbrella.mjs; do not edit.';
const THIN_LINE = /^export \* from '@margoengine\/[a-z0-9-]+(?:\/[a-z0-9/-]+)?';$/;

/** True when `text` is the generated banner plus `export * from '@margoengine/...';` lines and nothing else. */
export function isThinReexport(text) {
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trimEnd())
    .filter(Boolean);
  return lines.length >= 2 && lines[0] === BANNER && lines.slice(1).every((l) => THIN_LINE.test(l));
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/**
 * The export subpaths (`./bvh/lines`) a package.json change adds or removes, or `undefined` when it changes anything
 * else: another field, a changed value of an entry that stays, or an added entry not shaped like the generated
 * `{ types, import }` pair.
 */
export function exportsDelta(before, after) {
  let a, b;
  try {
    a = JSON.parse(before);
    b = JSON.parse(after);
  } catch {
    return undefined;
  }
  const { exports: ea = {}, ...restA } = a,
    { exports: eb = {}, ...restB } = b;
  if (!same(restA, restB)) return undefined;
  const added = Object.keys(eb).filter((k) => !(k in ea)),
    removed = Object.keys(ea).filter((k) => !(k in eb));
  for (const k of Object.keys(ea)) if (k in eb && !same(ea[k], eb[k])) return undefined;
  for (const k of added) {
    const v = eb[k];
    if (!v || typeof v !== 'object' || !same(Object.keys(v).sort(), ['import', 'types'])) return undefined;
  }
  return { added, removed };
}

/**
 * Whether the change to one umbrella file is only a re-export entry coming or going. `read(file)` gives
 * `{ before, after }` (a missing side is `null`); `usedBy(specifier)` says whether any file outside the umbrella still
 * imports `margoengine/<subpath>` (a removed entry that something imports could break that consumer, so it stays full).
 */
export function umbrellaChangeIsReexportOnly(file, read, usedBy = () => true) {
  if (!file.startsWith(UMBRELLA_DIR)) return false;
  const { before, after } = read(file);
  if (file === `${UMBRELLA_DIR}package.json`) {
    if (before == null || after == null) return false;
    const delta = exportsDelta(before, after);
    if (!delta) return false;
    return delta.removed.every((k) => !usedBy(`margoengine${k.slice(1)}`));
  }
  if (/^packages\/margoengine\/src\/.+\.ts$/.test(file)) {
    // Added or deleted thin files only: a rewritten one could point a live entry at another package.
    if (before != null && after != null) return false;
    const text = after ?? before;
    if (!isThinReexport(text)) return false;
    if (after == null) return !usedBy(`margoengine/${file.slice(UMBRELLA_DIR.length + 4, -3)}`);
    return true;
  }
  return false;
}

/** `read` and `usedBy` for a checkout: the texts at `base` and in the working tree, and a git grep for importers. */
export function changedUmbrellaReader(cwd, base, fs) {
  const git = (...args) => {
    try {
      return execFileSync('git', args, {
        cwd,
        encoding: 'utf8',
        maxBuffer: 1 << 28,
        stdio: ['ignore', 'pipe', 'ignore'],
      });
    } catch (error) {
      return error.status === 1 && args[0] === 'grep' ? '' : null;
    }
  };
  return {
    read: (file) => ({
      before: git('show', `${base}:${file}`),
      after: fs.existsSync(`${cwd}/${file}`) ? fs.readFileSync(`${cwd}/${file}`, 'utf8') : null,
    }),
    usedBy: (specifier) => {
      const escaped = specifier.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const hits = git(
        'grep',
        '-l',
        '-E',
        `['"\`]${escaped}(['"\`/])`,
        '--',
        '.',
        ':(exclude)packages/margoengine',
        ':(exclude)*.md',
        ':(exclude)api',
      );
      return hits === null ? true : hits.trim().length > 0;
    },
  };
}
