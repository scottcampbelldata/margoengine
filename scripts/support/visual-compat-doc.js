// The generated table in docs/webgl2-compat-demos.md, written by both steps of the WebGL2 compatibility run: the pixel
// step (scripts/visual-compat.mjs) owns the status and noise columns and the "Last recorded" line, the budget step
// (scripts/visual-compat-budget.mjs) the frame column. Rows not rerun keep their cells.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const docPath = resolve(import.meta.dirname, '../../docs/webgl2-compat-demos.md');
const start = '<!-- visual-compat table: generated by npm run visual:compat -- --write -->',
  end = '<!-- end of the visual-compat table -->';
const header = [
  '| Demo | View | On the WebGL2 layer | Native run-to-run (d > 2, mean) | Frame work native / layer; interval native / layer |',
  '| --- | --- | --- | --- | --- |',
];

/** The table's rows as `Map<id, [id, view, result, noise, frame]>` and its "Last recorded" line, from the doc's text. */
export function parseTable(doc) {
  const body = doc.split(start)[1].split(end)[0];
  const rows = new Map(
    [...body.matchAll(/^\| `([^`]+)` \|(.*)\|\s*$/gm)].map((m) => [
      m[1],
      [m[1], ...m[2].split(' | ').map((c) => c.trim())],
    ]),
  );
  return { rows, recorded: body.split(/\r?\n/).find((line) => line.startsWith('Last recorded')) ?? '' };
}

/** Joins rows and the "Last recorded" line back into the doc's text between its two markers. */
export function formatTable(doc, rows, recorded) {
  const [before, rest] = doc.split(start),
    after = rest.split(end)[1];
  const table = [
    recorded,
    '',
    ...header,
    ...[...rows.entries()]
      .sort(([x], [y]) => x.localeCompare(y))
      .map(([, [id, ...cells]]) => `| \`${id}\` | ${cells.join(' | ')} |`),
  ].join('\n');
  return `${before}${start}\n${table}\n${end}${after}`;
}

/**
 * Rewrites the table: `update(rows)` changes the rows in place and returns a new "Last recorded" line, or undefined to
 * keep the old one.
 */
export async function rewriteTable(update) {
  const doc = await readFile(docPath, 'utf8'),
    { rows, recorded } = parseTable(doc);
  await writeFile(docPath, formatTable(doc, rows, update(rows) ?? recorded));
}
