// Writes packages/ifc/src/schema-tree.ts and src/predefined-enums.ts: the IfcObjectDefinition subtype tree of IFC4 ADD2 TC1 and IFC4X3 ADD2, read
// from buildingSMART's published EXPRESS schemas (Standards-builds, IFC/RELEASE/.../EXPRESS), whose terms allow use in
// software development with attribution. The IFC2X3 TC1 EXPRESS file reserves all rights, so nothing is derived from
// it: IFC2X3 models use the IFC4 tree (see src/schema.ts).
// Usage: node packages/ifc/scripts/schema-tree.mjs <IFC4.exp> <IFC4X3_ADD2.exp>
// Each schema is one string of `Parent:Child,Child` groups joined by spaces, names without the `Ifc` prefix, in
// breadth-first order from ObjectDefinition, so the reader rebuilds every parent link in one pass.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const files = process.argv.slice(2);
if (files.length !== 2) {
  console.error('usage: node packages/ifc/scripts/schema-tree.mjs <IFC4.exp> <IFC4X3_ADD2.exp>');
  process.exitCode = 1;
} else generate(files);

function tree(path) {
  const source = readFileSync(path, 'utf8').replace(/\(\*[\s\S]*?\*\)/g, '');
  const schema = /^\s*SCHEMA\s+(\w+)\s*;/m.exec(source)?.[1];
  const children = new Map();
  for (const match of source.matchAll(/\bENTITY\s+(\w+)\b([^;]*);/g)) {
    const parent = /SUBTYPE\s+OF\s*\(\s*(\w+)\s*\)/.exec(match[2])?.[1];
    if (!parent) continue;
    (children.get(parent) ?? children.set(parent, []).get(parent)).push(match[1]);
  }
  const groups = [],
    queue = ['IfcObjectDefinition'];
  let count = 1;
  while (queue.length) {
    const parent = queue.shift();
    const list = (children.get(parent) ?? []).sort();
    if (!list.length) continue;
    count += list.length;
    queue.push(...list);
    groups.push(`${parent.slice(3)}:${list.map((c) => c.slice(3)).join(',')}`);
  }
  return { schema, text: groups.join(' '), count };
}

// Writes both generated files from the two schemas.
function generate(files) {
  const [ifc4, ifc4x3] = files.map(tree);
  const out = `// Generated by packages/ifc/scripts/schema-tree.mjs from buildingSMART's EXPRESS schemas ${ifc4.schema} (ADD2 TC1)
// and ${ifc4x3.schema}: the IfcObjectDefinition subtype tree (${ifc4.count} and ${ifc4x3.count} classes).
// Do not edit by hand. Each group is \`Parent:Child,Child\` without the \`Ifc\` prefix, breadth first.
export const IFC4_TREE = '${ifc4.text}';
export const IFC4X3_TREE = '${ifc4x3.text}';
`;
  const target = fileURLToPath(new URL('../src/schema-tree.ts', import.meta.url));
  writeFileSync(target, out);
  console.log(`${target}: ${ifc4.count} + ${ifc4x3.count} classes, ${out.length} bytes`);

  // The enumeration types of the attributes of IfcPreDefinedPropertySet subtypes (IfcDoorPanelProperties.PanelOperation
  // is an IfcDoorPanelOperationEnum): web-ifc returns enumeration values without their type, and IDS checks it.
  function predefinedEnums(path) {
    const source = readFileSync(path, 'utf8').replace(/\(\*[\s\S]*?\*\)/g, '');
    const enums = new Set([...source.matchAll(/\bTYPE\s+(\w+)\s*=\s*ENUMERATION\b/g)].map((m) => m[1]));
    const parent = new Map(),
      bodies = new Map();
    for (const m of source.matchAll(/\bENTITY\s+(\w+)\b([\s\S]*?)\bEND_ENTITY\s*;/g)) {
      const up = /SUBTYPE\s+OF\s*\(\s*(\w+)\s*\)/.exec(m[2])?.[1];
      if (up) parent.set(m[1], up);
      bodies.set(m[1], m[2].split(/\b(?:WHERE|DERIVE|INVERSE|UNIQUE)\b/)[0]);
    }
    const groups = [];
    for (const [name, body] of [...bodies].sort(([a], [b]) => a.localeCompare(b))) {
      let at = parent.get(name);
      while (at && at !== 'IfcPreDefinedPropertySet') at = parent.get(at);
      if (!at) continue;
      const attrs = [...body.matchAll(/^\s*(\w+)\s*:\s*(?:OPTIONAL\s+)?(\w+)\s*;/gm)].filter((a) => enums.has(a[2]));
      if (attrs.length) groups.push(`${name.slice(3)}:${attrs.map((a) => `${a[1]}=${a[2].slice(3)}`).join(',')}`);
    }
    return groups.join(' ');
  }
  const enumTarget = fileURLToPath(new URL('../src/predefined-enums.ts', import.meta.url));
  const enumOut = `// Generated by packages/ifc/scripts/schema-tree.mjs from buildingSMART's EXPRESS schemas ${ifc4.schema} (ADD2 TC1)
// and ${ifc4x3.schema}: the enumeration type of each enumerated attribute of the IfcPreDefinedPropertySet subtypes.
// Do not edit by hand. Each group is \`Class:Attribute=Enum,...\` without the \`Ifc\` prefix.
export const IFC4_PREDEFINED_ENUMS = '${predefinedEnums(files[0])}';
export const IFC4X3_PREDEFINED_ENUMS = '${predefinedEnums(files[1])}';
`;
  writeFileSync(enumTarget, enumOut);
  console.log(`${enumTarget}: ${enumOut.length} bytes`);
}
