// `npm run build:physics-kernel`: cargo, wasm-opt, raw deflate, then src/wasm.ts, so consumers need no Rust toolchain.
// The blueprint records a hash of the kernel's sources; tests/kernel-blueprint.test.js fails when a source moved on
// without a rebuild. Importing this file only reads; the build runs when it is the script node was asked to run.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync, inflateRawSync } from 'node:zlib';

const root = fileURLToPath(new URL('..', import.meta.url));
const kernel = resolve(root, 'kernel');
const repository = resolve(root, '../..');

/** The flags the blueprint is built with; a change to them is a change to the blueprint. */
export const RUSTFLAGS = '-C target-feature=+simd128';

/** Hash of everything that decides the blueprint's bytes; line endings do not count. */
export function kernelSourceHash() {
  const files = [
    'Cargo.toml',
    'Cargo.lock',
    ...readdirSync(resolve(kernel, 'src'))
      .filter((name) => name.endsWith('.rs'))
      .sort()
      .map((name) => `src/${name}`),
  ];
  const hash = createHash('sha256').update(RUSTFLAGS);
  for (const name of files)
    hash.update(`\0${name}\0`).update(readFileSync(resolve(kernel, name), 'utf8').replaceAll('\r\n', '\n'));
  return hash.digest('hex');
}

/** Column names and kinds in the order of the `columns!` table of kernel/src/layout.rs. */
export function kernelColumns() {
  const source = readFileSync(resolve(kernel, 'src/layout.rs'), 'utf8');
  const table = /^columns! \{([\s\S]*?)^\}/m.exec(source)[1];
  return [...table.matchAll(/^\s*([A-Z0-9_]+) (f32|u32) (\w+),/gm)].map(([, name, kind, rows]) => ({
    name: name.toLowerCase().replace(/_(\w)/g, (_, letter) => letter.toUpperCase()),
    kind,
    rows,
  }));
}

function build() {
  const target = resolve(kernel, 'target');
  execFileSync(
    'cargo',
    ['build', '--locked', '--manifest-path', resolve(kernel, 'Cargo.toml'), '--target', 'wasm32-unknown-unknown', '--release'],
    { stdio: 'inherit', env: { ...process.env, CARGO_TARGET_DIR: target, RUSTFLAGS } },
  );
  const wasmPath = resolve(target, 'wasm32-unknown-unknown/release/margoengine_physics_kernel.wasm');
  const optimized = wasmPath.replace('.wasm', '.optimized.wasm');
  execFileSync(
    process.execPath,
    [
      resolve(repository, 'node_modules/binaryen/bin/wasm-opt'),
      wasmPath,
      '-O3',
      '--enable-simd',
      '--enable-bulk-memory',
      '--enable-bulk-memory-opt',
      '--enable-nontrapping-float-to-int',
      '--strip-debug',
      '--strip-producers',
      '--strip-target-features',
      '-o',
      optimized,
    ],
    { stdio: 'inherit' },
  );
  const wasm = readFileSync(optimized);
  assert.ok(WebAssembly.validate(wasm), 'Invalid Wasm artifact');
  const text = wasm.toString('latin1');
  for (const leak of ['Users', 'Development', '.cargo', 'rustc'])
    assert.ok(!text.includes(leak), `The blueprint holds a build path (${leak})`);
  const compressed = deflateRawSync(wasm, { level: 9 });
  assert.deepEqual(inflateRawSync(compressed), wasm, 'Kernel compression must be lossless');
  writeFileSync(
    resolve(root, 'src/wasm.ts'),
    `// Generated by scripts/build-kernel.mjs: the kernel's raw-deflate blueprint; consumers need no Rust toolchain.
/** Hash of the kernel's sources this blueprint was built from. */
export const kernelSource: string = '${kernelSourceHash()}';
/** The kernel's columns in layout order: name, then 'f' for f32 or 'u' for u32, then its row class. */
export const kernelColumns: readonly (readonly [string, 'f' | 'u', number])[] = ${JSON.stringify(columnTable())};
export const wasmBase64: string = '${compressed.toString('base64')}';
`,
  );
  console.log(`physics kernel: ${wasm.length} B raw, ${compressed.length} B deflated`);
}

function columnTable() {
  const classes = [...new Set(kernelColumns().map((column) => column.rows))];
  return kernelColumns().map(({ name, kind, rows }) => [name, kind === 'f32' ? 'f' : 'u', classes.indexOf(rows)]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
