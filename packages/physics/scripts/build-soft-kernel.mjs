// `node packages/physics/scripts/build-soft-kernel.mjs`: cargo, wasm-opt, raw deflate, then src/soft-wasm.ts, so consumers
// need no Rust toolchain. The record beside it (scripts/wasm-blueprints.mjs) holds a hash of the sources it was built from.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync, inflateRawSync } from 'node:zlib';
import { committedBlueprint } from '../../../scripts/committed-blueprint.mjs';
import { blueprintRustEnv } from '../../../scripts/rust-wasm-env.mjs';
import { BLUEPRINTS, writeRecord } from '../../../scripts/wasm-blueprints.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const kernel = resolve(root, 'soft-kernel');
const repository = resolve(root, '../..');

/** The flags the blueprint is built with; a change to them is a change to the blueprint. */
export const RUSTFLAGS = '-C target-feature=+simd128';

/** The names of the columns, in the order of the `columns!` list of soft-kernel/src/api.rs. */
export function softColumns() {
  const source = readFileSync(resolve(kernel, 'src/api.rs'), 'utf8');
  const body = /^columns! \{([\s\S]*?)^\}/m.exec(source)[1];
  return [...body.matchAll(/[a-z_0-9]+/g)].map(([name]) => name);
}

/** The shared kernel parts (cloth contacts) are a path dependency outside the crate: cargo names their files by absolute path, so
 * that folder is remapped too, and the bytes do not depend on where the repository is checked out. */
function kernelEnv() {
  const common = resolve(root, 'kernel-common');
  const env = blueprintRustEnv(kernel, RUSTFLAGS);
  env.RUSTFLAGS += ` --remap-path-prefix=${common}=physics/kernel-common`;
  return env;
}

function build() {
  execFileSync(
    'cargo',
    [
      'build',
      '--locked',
      '--manifest-path',
      resolve(kernel, 'Cargo.toml'),
      '--target',
      'wasm32-unknown-unknown',
      '--release',
    ],
    { stdio: 'inherit', env: kernelEnv() },
  );
  const wasmPath = resolve(kernel, 'target/wasm32-unknown-unknown/release/margoengine_soft_kernel.wasm');
  const optimized = wasmPath.replace('.wasm', '.optimized.wasm');
  execFileSync(
    process.execPath,
    [
      resolve(repository, 'node_modules/binaryen/bin/wasm-opt'),
      wasmPath,
      '-O3',
      '--enable-simd',
      '--enable-bulk-memory',
      '--enable-bulk-memory-opt',
      '--enable-nontrapping-float-to-int',
      '--strip-debug',
      '--strip-producers',
      '--strip-target-features',
      '-o',
      optimized,
    ],
    { stdio: 'inherit' },
  );
  const wasm = readFileSync(optimized);
  assert.ok(WebAssembly.validate(wasm), 'Invalid Wasm artifact');
  const text = wasm.toString('latin1');
  for (const leak of ['Users', 'Development', '.cargo', 'rustc'])
    assert.ok(!text.includes(leak), `The blueprint holds a build path (${leak})`);
  // The committed string stays when it still inflates to this kernel, so a rebuild gives the same bytes on every machine.
  const compressed = committedBlueprint(
    resolve(root, 'src/soft-wasm.ts'),
    'wasmBase64',
    wasm,
    inflateRawSync,
    (bytes) => deflateRawSync(bytes, { level: 9 }),
  );
  assert.deepEqual(inflateRawSync(compressed), wasm, 'Kernel compression must be lossless');
  writeFileSync(
    resolve(root, 'src/soft-wasm.ts'),
    `// Generated by scripts/build-soft-kernel.mjs: the soft body kernel's raw-deflate blueprint; consumers need no Rust toolchain.
/** The kernel's columns, by the id \`soft_column\` takes. */
export const softColumns: readonly string[] = ${JSON.stringify(softColumns())};
export const wasmBase64: string = '${compressed.toString('base64')}';
`,
  );
  writeRecord(BLUEPRINTS.find((entry) => entry.name === 'soft-kernel'));
  console.log(`soft kernel: ${wasm.length} B raw, ${compressed.length} B deflated`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
