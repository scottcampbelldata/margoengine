/** Close the mirror halves below deck. A stride of two coarsens both measured grid directions. */
export function kvlcc2Hull({ length, freeboard, centre, stride }) {
  const vertices = [];
  const indices = [];
  const selected = (_value, index, array) => index % stride === 0 || index === array.length - 1;
  const rows = HALF_HULL.filter(selected).map((row) => row.filter(selected));
  const deck = rows.at(-1).map(([x, breadth]) => [x, breadth, freeboard / length]);
  for (const row of [...rows, deck]) {
    for (const side of [1, -1]) {
      for (const [x, breadth, y] of row) {
        vertices.push(length * x - centre[0], length * y - centre[1], side * length * breadth);
      }
    }
  }
  const width = deck.length;
  const rowSize = 2 * width;
  const quad = (a, b, c, d, reverse) => {
    if (reverse) indices.push(a, c, b, a, d, c);
    else indices.push(a, b, c, a, c, d);
  };
  for (let row = 0; row < rows.length; row++) {
    const lower = row * rowSize;
    const upper = lower + rowSize;
    for (let column = 0; column < width - 1; column++) {
      const a = lower + column;
      const b = a + 1;
      const d = upper + column;
      const c = d + 1;
      quad(a, b, c, d, true);
      quad(a + width, b + width, c + width, d + width, false);
    }
    quad(lower, lower + width, upper + width, upper, false);
    quad(lower + width - 1, upper - 1, upper + rowSize - 1, upper + width - 1, true);
  }
  const deckOffset = rows.length * rowSize;
  for (let i = 0; i < width - 1; i++) {
    quad(i, i + 1, i + 1 + width, i + width, false);
    const a = deckOffset + i;
    quad(a, a + 1, a + 1 + width, a + width, true);
  }
  return { vertices: Float64Array.from(vertices), indices: Uint32Array.from(indices) };
}
