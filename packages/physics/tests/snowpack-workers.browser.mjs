import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { build, preview } from 'vite';
import { openBrowser } from '../../../scripts/browser.js';

const output = resolve('test-results');
await mkdir(output, { recursive: true });
const root = await mkdtemp(join(output, 'snowpack-worker-consumer-'));
try {
  await writeFile(join(root, 'index.html'), '<script type="module" src="./index.js"></script>');
  await writeFile(
    join(root, 'index.js'),
    `
    window.snowpackWorkers = new Promise((resolve, reject) => {
      const worker = new Worker(new URL('./world.js', import.meta.url), { type: 'module' });
      worker.onmessage = ({ data }) => { worker.terminate(); resolve(data); };
      worker.onerror = ({ message }) => { worker.terminate(); reject(new Error(message)); };
    });
  `,
  );
  await writeFile(
    join(root, 'world.js'),
    `
    import { followSnowpack } from '../../packages/physics/tests/fixtures/snowpack-workers.mjs';
    const BrowserWorker = globalThis.Worker;
    let starts = 0, stops = 0;
    globalThis.Worker = class extends BrowserWorker {
      constructor(url, config) { super(url, config); starts++; }
      terminate() { stops++; super.terminate(); }
    };
    async function verify() {
      const scalar = await followSnowpack(17, 13, 1);
      const parallel = await followSnowpack(17, 13, 4);
      return { isolated: crossOriginIsolated, helpers: [starts, stops], scalar, parallel };
    }
    void verify().then(
      result => postMessage(result),
      error => postMessage({ error: error.stack ?? String(error) }),
    );
  `,
  );
  await build({
    root,
    configFile: false,
    publicDir: false,
    logLevel: 'warn',
    build: { target: 'es2022' },
    worker: { format: 'es' },
  });
  const assets = join(root, 'dist/assets');
  const files = await readdir(assets);
  for (const variant of ['snowpack-kernel', 'snowpack-kernel-shared']) {
    const match = files.filter(
      (name) =>
        name.startsWith(variant + '-') &&
        name.endsWith('.wasm') &&
        (variant !== 'snowpack-kernel' || !/^snowpack-kernel-shared-/.test(name)),
    );
    assert.equal(match.length, 1, `Keep ${variant} as a separate packaged Wasm asset.`);
    assert.deepEqual(
      await readFile(join(assets, match[0])),
      await readFile(new URL(`../dist/${variant}.wasm`, import.meta.url)),
    );
  }
  assert.equal(files.filter((name) => /^solver-phase-thread-.*\.js$/.test(name)).length, 1);
  const app = await preview({
    root,
    configFile: false,
    logLevel: 'warn',
    preview: {
      host: '127.0.0.1',
      port: 0,
      headers: { 'Cross-Origin-Opener-Policy': 'same-origin', 'Cross-Origin-Embedder-Policy': 'require-corp' },
    },
  });
  try {
    const { page, close } = await openBrowser({
      startPath: '/tools/shot/blank.html',
      port: 'free',
      softwareAdapterOk: true,
    });
    try {
      const address = app.httpServer.address();
      assert.ok(address && typeof address === 'object');
      await page.goto('http://127.0.0.1:' + address.port + '/');
      const result = await page.evaluate(() =>
        Promise.race([
          window.snowpackWorkers,
          new Promise((_, reject) =>
            setTimeout(() => reject(new Error('The packaged snowpack helpers did not finish.')), 20_000),
          ),
        ]),
      );
      assert.equal(result.error, undefined, result.error);
      assert.ok(result.isolated);
      assert.deepEqual(result.helpers, [3, 3]);
      const { state, work } = result.parallel.accepted;
      assert.deepEqual(state, result.scalar.accepted.state);
      assert.deepEqual(result.parallel.accepted, result.parallel.replay);
      assert.deepEqual(result.scalar.accepted, result.scalar.replay);
      for (const port of Object.values(state.fields))
        assert.deepEqual(port.cell, [1_165_900_000, -1_048_500_000, 1_982_700_000]);
      assert.ok(state.cliff.corniceMass > 0);
      const latest = work.at(-1);
      assert.equal(latest.threads, 4);
      assert.equal(latest.columns, 221);
      assert.equal(latest.layers, 1105);
      assert.ok(latest.conductionInterfaces > 663);
      assert.ok(latest.pairedInterfaces > 0.85 * latest.conductionInterfaces);
      assert.equal(latest.bisectionIterations, 54 * latest.conductionInterfaces);
      assert.deepEqual(latest.workers.map(({ columns }) => columns), [54, 56, 54, 57]);
      assert.ok(latest.workers.every(({ pairedInterfaces }) => pairedInterfaces > 0));
      console.log('ICE-01 packaged snow-column conduction work', state.snapshot.hash, latest);
    } finally {
      await close();
    }
  } finally {
    await app.close();
  }
} finally {
  // mkdtemp created this exact child of the ignored test-results directory.
  await rm(root, { recursive: true, force: true });
}
