// Builds native/meshopt-simd for wasm32 with SIMD and embeds it in src/meshopt-simd-wasm.ts, so nobody who installs or
// builds the package needs Rust. Run it after changing the crate: `node scripts/meshopt-simd-build.mjs`. Needs cargo and the
// wasm32-unknown-unknown target. tests/meshopt-simd.test.js fails when the source and the embedded module drift apart.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const crate = fileURLToPath(new URL('../native/meshopt-simd/', import.meta.url)),
  target = fileURLToPath(new URL('../target/', import.meta.url));
execFileSync('cargo', ['build', '--release', '--locked'], {
  cwd: crate,
  stdio: 'inherit',
  timeout: 300_000,
  env: { ...process.env, CARGO_TARGET_DIR: target },
});
const wasm = readFileSync(`${target}wasm32-unknown-unknown/release/margoengine_meshopt_simd.wasm`),
  source = readFileSync(`${crate}src/lib.rs`, 'utf8').replace(/\r\n/g, '\n'),
  sha = createHash('sha256').update(source).digest('hex');
writeFileSync(
  new URL('../src/meshopt-simd-wasm.ts', import.meta.url),
  `// Generated by scripts/meshopt-simd-build.mjs from native/meshopt-simd; source sha256 ${sha}. Do not edit.\n` +
    `export const MESHOPT_SIMD_WASM: string =\n  '${wasm.toString('base64')}';\n`,
);
console.log(`${wasm.length} bytes of Wasm embedded`);
