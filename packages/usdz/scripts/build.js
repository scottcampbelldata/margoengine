import {execFileSync} from 'node:child_process';
import {copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {build} from 'vite';
import {buildWorkers} from '../../../scripts/build-workers.js';
const root=fileURLToPath(new URL('..',import.meta.url)),repository=resolve(root,'../..');
await copyFile(resolve(repository,'LICENSE'),resolve(root,'LICENSE'));
await build({root,configFile:false,publicDir:false,logLevel:'warn',build:{outDir:resolve(root,'dist'),emptyOutDir:true,target:'es2022',lib:{entry:{index:resolve(root,'src/index.ts'),worker:resolve(root,'src/worker.ts')},formats:['es'],fileName:(_,name)=>name+'.js'},rollupOptions:{external:id=>/^@margoengine\/(core|gltf-pro|loaders)(\/|$)/.test(id)}}});
await buildWorkers(root);
execFileSync(process.execPath,[resolve(repository,'node_modules/typescript/bin/tsc'),'-p',resolve(root,'tsconfig.json')],{stdio:'inherit'});
