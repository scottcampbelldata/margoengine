// The compatibility layer costs WebGPU users nothing (roadmap condition, Scott 2026-10-27): no source file of another
// package names it, no package depends on it except the umbrella's own alias entry, the built core, stage, React and
// umbrella root entries reach no module of it, and importing it changes no global. Since no other package's source or manifest
// refers to it, every other package builds to the same bytes with or without it installed.
import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..', '..');
const NAME = '@margoengine/webgl2-compat';
/** The umbrella's generated alias of each entry, and what each one re-exports. */
const ENTRIES = ['', '/adapter', '/compute', '/device', '/glsl', '/wgsl', '/xr'];
const UMBRELLA = ENTRIES.map((e) => `packages/margoengine/src/webgl2-compat${e}.ts`);
const ALIASED = ENTRIES.map((e) => NAME + e);

test('no other package source names the compatibility layer', () => {
  let out = '';
  try {
    out = execFileSync('git', ['grep', '-l', '-F', 'webgl2-compat', '--', 'packages/*/src/**', 'packages/shared/**'], {
      cwd: root,
      encoding: 'utf8',
    });
  } catch (error) {
    if (error.status !== 1) throw error; // git grep exits 1 when nothing matches
  }
  const files = out
    .split('\n')
    .filter(Boolean)
    .filter((f) => !f.startsWith('packages/webgl2-compat/') && !UMBRELLA.includes(f));
  assert.deepEqual(files, []);
});

test('only the umbrella depends on it', () => {
  const out = execFileSync('git', ['ls-files', 'packages/*/package.json'], { cwd: root, encoding: 'utf8' });
  for (const file of out.split('\n').filter(Boolean)) {
    const m = JSON.parse(readFileSync(join(root, file), 'utf8'));
    if (m.name === NAME || m.name === 'margoengine') continue;
    const all = { ...m.dependencies, ...m.peerDependencies, ...m.optionalDependencies, ...m.devDependencies };
    assert.ok(!(NAME in all), `${m.name} must not depend on ${NAME}`);
  }
  for (const [i, file] of UMBRELLA.entries())
    assert.equal(
      readFileSync(join(root, file), 'utf8').replace(/\r\n/g, '\n'),
      `// Generated by scripts/umbrella.mjs; do not edit.\nexport * from '${ALIASED[i]}';\n`,
    );
});

/**
 * Every specifier the dist modules reachable from `entry` import, statically or (unless `staticOnly`) with a literal
 * import().
 */
function distReach(entry, staticOnly = false) {
  const seen = new Set(),
    specifiers = new Set(),
    queue = [entry];
  let all = '';
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    const text = readFileSync(file, 'utf8');
    all += text;
    const pattern = staticOnly
      ? /(?:\bfrom\s*|\bimport\s+)["']([^"']+)["']/g
      : /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)["'`]([^"'`]+)["'`]/g;
    for (const m of text.matchAll(pattern)) {
      const s = m[1];
      if (s.startsWith('.')) {
        const next = resolve(dirname(file), s);
        if (existsSync(next)) queue.push(next);
      } else specifiers.add(s);
    }
  }
  return { files: seen.size, specifiers, text: all };
}

test('the built core, stage, React and umbrella roots reach no module of the layer', () => {
  for (const pkg of ['core', 'stage', 'react', 'margoengine']) {
    const entry = join(root, 'packages', pkg, 'dist', 'index.js');
    assert.ok(existsSync(entry), `${pkg} is not built; run npm run build:packages first`);
    const { files, text } = distReach(entry);
    assert.ok(files > 0);
    assert.ok(!text.includes('webgl2-compat'), `${pkg}'s built root or a module it reaches names the layer`);
  }
});

test("packages' WebGL2 routes load by import() only: their roots' static graphs never reach the route", () => {
  // Packages find the layer by its adapter vendor (packages/shared/compat.js) and import their route lazily, so a page
  // with WebGPU downloads none of it.
  for (const pkg of ['dof', 'splats', 'culling']) {
    const entry = join(root, 'packages', pkg, 'dist', 'index.js');
    const all = distReach(entry),
      fixed = distReach(entry, true);
    assert.match(all.text, /margo-webgl2/, `${pkg} detects the layer`);
    // The route chunk is the compat chunk the root imports with import(); with several entries the build may also split
    // packages/shared/compat.js into a chunk of the same name stem (culling: its root and its dynamic entry share it).
    const chunk = readdirSync(join(root, 'packages', pkg, 'dist')).find(
      (f) =>
        /^compat-[\w-]+\.js$/.test(f) &&
        new RegExp(`import\\(\\s*["'\`]\\./${f.replace('.', '\\.')}["'\`]\\s*\\)`).test(all.text),
    );
    assert.ok(chunk, `${pkg} builds its route into a chunk of its own`);
    assert.match(
      all.text,
      new RegExp(`import\\(\\s*["'\`]\\./${chunk.replace('.', '\\.')}["'\`]\\s*\\)`),
      `${pkg} imports it lazily`,
    );
    const route = readFileSync(join(root, 'packages', pkg, 'dist', chunk), 'utf8');
    assert.ok(!fixed.text.includes(route.slice(0, 400)), `${pkg}'s root reaches its route statically`);
    assert.ok(all.text.includes(route.slice(0, 400)), 'the route is reached through import()');
  }
});

test('importing any entry touches no global and imports nothing else; the root loads the layer only in install()', async () => {
  for (const entry of ['index.js', 'wgsl.js', 'glsl.js', 'device.js', 'xr.js']) {
    const before = new Set(Object.getOwnPropertyNames(globalThis));
    await import(`../dist/${entry}`);
    const added = Object.getOwnPropertyNames(globalThis).filter((k) => !before.has(k));
    assert.deepEqual(added, [], entry);
    const { specifiers } = distReach(join(import.meta.dirname, '..', 'dist', entry));
    assert.deepEqual([...specifiers], [], entry);
  }
  // The root's static graph is the probe and install() alone: the device, back end and front end load by import()
  // inside install(), so a page that only probes downloads none of them.
  const front = distReach(join(import.meta.dirname, '..', 'dist', 'index.js'), true);
  assert.equal(front.files, 1, 'the root entry statically imports another module');
  assert.ok(!front.text.includes('WGSLError'), 'the root entry reaches the WGSL front end');
  assert.match(front.text, /import\(\s*["']\.\/device\.js["']\s*\)/, 'install() loads ./device.js on demand');
});
