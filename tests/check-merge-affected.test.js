// ---- The umbrella: re-export entries coming or going are not a floor change. ----
const BANNER = '// Generated by scripts/umbrella.mjs; do not edit.\n';
const pkgJson = (exportsMap, extra = {}) => JSON.stringify({ name: 'margoengine', ...extra, exports: exportsMap });
const entry = (name) => ({ types: `./dist/${name}.d.ts`, import: `./dist/${name}.js` });
const BEFORE = pkgJson({ '.': entry('index'), './a': entry('a') }, { dependencies: { '@margoengine/a': '1.0.0' } });
const umbrella =
  (texts, used = []) =>
  (file) =>
    umbrellaChangeIsReexportOnly(
      file,
      (f) => texts[f] ?? { before: null, after: null },
      (s) => used.includes(s),
    );
const umbrellaRun = (files, texts, used) => run(files, { umbrellaReexport: umbrella(texts, used) });
const PJ = 'packages/margoengine/package.json';

test('an umbrella change that only adds re-export entries runs the changed packages, not everything', () => {
  const texts = {
    [PJ]: {
      before: BEFORE,
      after: pkgJson(
        { '.': entry('index'), './a': entry('a'), './a/lines': entry('a/lines') },
        { dependencies: { '@margoengine/a': '1.0.0' } },
      ),
    },
    'packages/margoengine/src/a/lines.ts': {
      before: null,
      after: `${BANNER}export * from '@margoengine/a/lines';
`,
    },
  };
  const result = umbrellaRun(
    [PJ, 'packages/margoengine/src/a/lines.ts', 'packages/margoengine/README.md', 'packages/d/src/x.ts'],
    texts,
  );
  assert.equal(result.mode, 'affected', result.reason);
  assert.deepEqual(result.changed, ['d']);
  assert.deepEqual(result.hits.sort(), ['gpu/d', 'gpu/root/unmapped']);
  // Without the callback the same files are the full run (the bug).
  assert.equal(run([PJ, 'packages/d/src/x.ts']).mode, 'full');
});

